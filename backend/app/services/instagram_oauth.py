"""Business Login for Instagram — the official OAuth flow.

Until now a client connected an account by pasting an access token they generated by
hand in the Meta developer dashboard (BYOT). That works, but it is a terrible onboarding
step and Meta's App Review explicitly requires the reviewer to see the real consent
screen, so Advanced Access can never be granted without this flow.

Shape of the exchange (Instagram-login apps live on their own hosts, NOT graph.facebook.com):
  1. send the user to  www.instagram.com/oauth/authorize
  2. Meta redirects back with ``code``  ->  api.instagram.com/oauth/access_token
     gives a SHORT-lived token (1 hour)
  3. graph.instagram.com/access_token?grant_type=ig_exchange_token upgrades it to a
     ~60-day long-lived token, which is what we store.

``state`` is an HMAC-signed, short-lived blob (same secret/scheme as the dashboard's
auth token) so the callback can trust which brand the operator picked without keeping
server-side session state.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import time
from typing import Any
from urllib.parse import urlencode

import httpx

from app.config import Settings

AUTHORIZE_URL = "https://www.instagram.com/oauth/authorize"
TOKEN_URL = "https://api.instagram.com/oauth/access_token"
LONG_LIVED_URL = "https://graph.instagram.com/access_token"

# Least-privilege: reading comments is all the monitoring product needs. Messaging
# scopes would widen the App Review surface for no benefit.
DEFAULT_SCOPES = ("instagram_business_basic", "instagram_business_manage_comments")

STATE_MAX_AGE_SECONDS = 900


class InstagramOAuthError(RuntimeError):
    """Raised with a message that is safe to show the operator in the dashboard."""


def _b64e(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode().rstrip("=")


def _b64d(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def _sign(secret: str, body: str) -> str:
    return _b64e(hmac.new(secret.encode(), body.encode(), hashlib.sha256).digest())


def encode_state(settings: Settings, payload: dict[str, Any]) -> str:
    body = _b64e(json.dumps({**payload, "iat": int(time.time())}, separators=(",", ":")).encode())
    return f"{body}.{_sign(settings.jwt_secret, body)}"


def decode_state(settings: Settings, state: str | None) -> dict[str, Any]:
    if not state or "." not in state:
        raise InstagramOAuthError("state yaroqsiz")
    body, _, signature = state.partition(".")
    if not hmac.compare_digest(_sign(settings.jwt_secret, body), signature):
        raise InstagramOAuthError("state imzosi mos kelmadi")
    try:
        payload = json.loads(_b64d(body))
    except (ValueError, json.JSONDecodeError) as exc:
        raise InstagramOAuthError("state o'qib bo'lmadi") from exc
    if int(time.time()) - int(payload.get("iat", 0)) > STATE_MAX_AGE_SECONDS:
        raise InstagramOAuthError("ulanish havolasi eskirgan — qaytadan urinib ko'ring")
    return payload


def build_authorize_url(
    app_id: str,
    redirect_uri: str,
    state: str,
    *,
    scopes: tuple[str, ...] = DEFAULT_SCOPES,
) -> str:
    if not app_id:
        raise InstagramOAuthError("IG_APP_ID sozlanmagan")
    query = urlencode(
        {
            "client_id": app_id,
            "redirect_uri": redirect_uri,
            "response_type": "code",
            "scope": ",".join(scopes),
            "state": state,
        }
    )
    return f"{AUTHORIZE_URL}?{query}"


def _meta_error(payload: Any, fallback: str) -> str:
    if isinstance(payload, dict):
        err = payload.get("error")
        if isinstance(err, dict) and err.get("message"):
            return str(err["message"])
        for key in ("error_message", "error_description", "error_type"):
            if payload.get(key):
                return str(payload[key])
    return fallback


def exchange_code_for_token(
    app_id: str,
    app_secret: str,
    redirect_uri: str,
    code: str,
) -> dict[str, Any]:
    """Authorization code -> short-lived (1 hour) Instagram user token."""
    try:
        response = httpx.post(
            TOKEN_URL,
            data={
                "client_id": app_id,
                "client_secret": app_secret,
                "grant_type": "authorization_code",
                "redirect_uri": redirect_uri,
                "code": code,
            },
            timeout=20.0,
        )
    except httpx.HTTPError as exc:
        raise InstagramOAuthError(f"Meta bilan bog'lanib bo'lmadi: {exc}") from exc
    try:
        payload = response.json()
    except ValueError:
        payload = None
    if response.status_code >= 400:
        raise InstagramOAuthError(_meta_error(payload, f"token almashinuvi xatosi (HTTP {response.status_code})"))
    # Instagram-login apps answer {"data": [{...}]}; the older flat shape is still
    # returned by some versions, so accept both.
    if isinstance(payload, dict) and isinstance(payload.get("data"), list) and payload["data"]:
        payload = payload["data"][0]
    if not isinstance(payload, dict) or not payload.get("access_token"):
        raise InstagramOAuthError("Meta access_token qaytarmadi")
    return {
        "access_token": str(payload["access_token"]),
        "user_id": str(payload.get("user_id") or ""),
        "permissions": payload.get("permissions"),
    }


def exchange_for_long_lived(app_secret: str, short_token: str) -> dict[str, Any]:
    """Short-lived -> ~60-day long-lived token (refreshable while it stays in use)."""
    try:
        response = httpx.get(
            LONG_LIVED_URL,
            params={
                "grant_type": "ig_exchange_token",
                "client_secret": app_secret,
                "access_token": short_token,
            },
            timeout=20.0,
        )
    except httpx.HTTPError as exc:
        raise InstagramOAuthError(f"Uzoq muddatli token olinmadi: {exc}") from exc
    try:
        payload = response.json()
    except ValueError:
        payload = None
    if response.status_code >= 400 or not isinstance(payload, dict) or not payload.get("access_token"):
        raise InstagramOAuthError(_meta_error(payload, "uzoq muddatli token olinmadi"))
    return {
        "access_token": str(payload["access_token"]),
        "expires_in": int(payload.get("expires_in") or 0),
    }


def parse_signed_request(app_secret: str, signed_request: str | None) -> dict[str, Any]:
    """Meta signs deauthorize / data-deletion callbacks as ``sig.payload``."""
    if not signed_request or "." not in signed_request:
        raise InstagramOAuthError("signed_request yo'q")
    signature, _, payload_part = signed_request.partition(".")
    expected = _b64e(hmac.new(app_secret.encode(), payload_part.encode(), hashlib.sha256).digest())
    if not hmac.compare_digest(expected, signature):
        raise InstagramOAuthError("signed_request imzosi mos kelmadi")
    try:
        return json.loads(_b64d(payload_part))
    except (ValueError, json.JSONDecodeError) as exc:
        raise InstagramOAuthError("signed_request o'qib bo'lmadi") from exc
